 await page.getByRole('button',{name:'CHỮ HOA'}).click();
 await expect(area).toHaveValue('HELLO WORLD!\n\nGLOBAL WARMING.');
 await page.reload();await page.getByRole('button',{name:'Mở bộ công cụ tức thì'}).click();await enter(page,11);
