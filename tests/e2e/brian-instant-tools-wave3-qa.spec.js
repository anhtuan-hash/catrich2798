test('Calculator safely evaluates arithmetic, rejects Javascript and stores history',async({page})=>{
 await enter(page,12);
 const input=page.locator('#bit-w3-expression');
 await input.fill('12*(3+2)');
 await page.getByRole('button',{name:'=',exact:true}).click();
 await expect(input).toHaveValue('60');
 await expect(page.locator('.bit-w3-history-row')).toHaveCount(1);
 await input.fill('200*15%');
 await page.getByRole('button',{name:'=',exact:true}).click();
 await expect(input).toHaveValue('30');
 await input.fill('alert(1)');
 await page.getByRole('button',{name:'=',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('không hợp lệ');
 await expect(page.locator('.bit-w3-history-row')).toHaveCount(2);
});
test('Quick Links rejects unsafe URLs and only stores safe HTTPS links',async({page})=>{
 await enter(page,13);
 await page.locator('#bit-w3-link-name').fill('School site');
 await page.locator('#bit-w3-link-url').fill('javascript:alert(1)');
 await page.getByRole('button',{name:'Thêm',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('không hợp lệ');
 await expect(page.locator('.bit-w3-link-row')).toHaveCount(0);
 await page.locator('#bit-w3-link-url').fill('https://example.com');
 await page.getByRole('button',{name:'Thêm',exact:true}).click();
 await expect(page.locator('.bit-w3-link-row')).toHaveCount(1);
 await expect(page.locator('.bit-w3-link-row a')).toHaveAttribute('href','https://example.com/');
 await expect(page.locator('.bit-w3-link-row a')).toHaveAttribute('rel','noopener noreferrer');
});
