import {test,expect} from '@playwright/test';
const url='/tests/fixtures/brian-instant-tools-qa.html';
test.beforeEach(async({page})=>{
 await page.route('https://**/*',route=>route.abort('blockedbyclient'));
 await page.goto(url);
 await page.getByRole('button',{name:'Mở bộ công cụ tức thì'}).click();
 await expect(page.locator('.bit-app-card')).toHaveCount(20);
});
const enter=(page,id)=>page.locator('.bit-app-card').nth(id).click();
test('Reveal Cards use real front and back 3D surfaces after a click',async({page})=>{
 await enter(page,8);
 const card=page.locator('.bit-w2-reveal-card').first();
 await expect(card.locator('.bit-w2-reveal-front')).toBeVisible();
 await expect(card.locator('.bit-w2-reveal-back')).toHaveCount(1);
 const backface=await card.locator('.bit-w2-reveal-back').evaluate(el=>getComputedStyle(el).backfaceVisibility);
 expect(backface).toBe('hidden');
 await card.click();
 await expect(card).toHaveClass(/is-flipped/);
 await expect(card).toHaveAttribute('aria-pressed','true');
 await card.click();
 await expect(card).not.toHaveClass(/is-flipped/);
});
