import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read=(p)=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const nav=read('src/components/GlobalCompactNavigation.jsx');
const frame=read('src/components/GlobalFlatNavigation.jsx');
const reports=read('src/components/GlobalReportsNavigationTab.jsx');
const ttcm=read('src/components/GlobalTtcmNavigationTab.jsx');
const attendance=read('src/components/GlobalAttendanceNavigationTab.jsx');
const css=read('src/components/GlobalNavigationUtilityIcons.css');
test('three accessible icons replace Utilities dropdown without changing destinations',()=>{
  assert.ok(nav.includes('brian-nav__utility-reports')&&nav.includes('brian-nav__utility-ttcm'));
  assert.ok(nav.includes('brian-nav__utility-admin-icon')&&nav.includes('isAdmin ?'));
  assert.ok(nav.includes("openRoute('#/admin', t.admin, event)"));
  assert.ok(!nav.includes('brian-nav__utilities-trigger'));
  assert.ok(!nav.includes('brian-nav-utilities-popover'));
  assert.ok(frame.includes("import './GlobalNavigationUtilityIcons.css'"));
  assert.ok(!frame.includes("import './GlobalNavigationUtilitiesDropdown.css'"));
  assert.ok(frame.includes('<GlobalLessonCheckNavigationTab {...props} />'));
  assert.ok(frame.includes('<GlobalGradebookNavigationTab {...props} />'));
});
test('existing countdown, notifications, TTCM modals, permission gates and attendance persist',()=>{
  assert.ok(reports.includes("document.querySelector('.brian-nav__utility-reports')"));
  assert.ok(reports.includes("hasToolAccess(currentUser, 'brian-team')"));
  assert.ok(reports.includes("target: '#/tool/brian-team'"));
  assert.ok(reports.includes('loadMonthlyReportDeadline'));
  assert.ok(reports.includes('window.setInterval(() => setNow(Date.now()), 1000)'));
  assert.ok(ttcm.includes("document.querySelector('.brian-nav__utility-ttcm')"));
  assert.ok(ttcm.includes('brian-nav__ttcm-badge'));
  assert.ok(ttcm.includes('const tab = createPortal('));
  assert.ok(ttcm.includes('const panel = open && typeof document !== \'undefined\' ? createPortal('));
  assert.ok(attendance.includes('data-nav-key="attendance"'));
  assert.ok(nav.includes('reportUnreadCount')&&nav.includes('adminUnreadCount'));
});
test('icon CSS leaves overlay dialogs alone and preserves the live status indicators',()=>{
  assert.ok(css.includes('.brian-nav__utility-reports > button::before'));
  assert.ok(css.includes('.brian-nav__utility-ttcm > button::before'));
  assert.ok(css.includes('brian-nav__reports-countdown'));
  assert.ok(css.includes('brian-nav__ttcm-badge'));
  assert.ok(css.includes('brian-nav__utility-badge'));
  assert.doesNotMatch(css,/\.ttcm-m3-layer\s*\{|\.attendance-layer\s*\{/);
});
