assert.equal(frameFromCorners('tiny',{x:0,y:0},{x:120,y:60}),null);
assert.deepEqual(normalizeBoardFrames([a,a,b]).map(f=>f.id),['frame-a','frame-b']);
assert.equal(normalizeBoardFrames(Array.from({length:50},(_,i)=>({...a,id:'k'+i}))).length,32);
assert.equal(nextFramePlacement([a]).x,a.x+a.width+120);
assert.equal(adjacentFrameIndex([a,b],a.id,1),1);
assert.equal(adjacentFrameIndex([a,b],b.id,-1),0);
assert.equal(adjacentFrameIndex([a,b],b.id,1),1);
assert.equal(adjacentFrameIndex([],null,1),-1);
assert.deepEqual(viewportForFrame(a),{x:2000,y:1200,width:1600,height:900});
assert.deepEqual(cameraForViewport(viewportForFrame(a)),{camera:{x:2000,y:1200},zoom:1});
assert.equal(safeBoardViewport({x:999999,y:-999999,width:999999,height:0}).x,100000);
assert.equal(safeBoardViewport({x:999999,y:-999999,width:999999,height:0}).y,-100000);
lesson.pages[0].frames=[a,b];
lesson.pages[0].objects=[
 {kind:'text',id:'t-public',x:2210,y:1340,text:'Frame title',studentVisible:true},
 {kind:'text',id:'t-private',x:2320,y:1400,text:'SECRET_TEACHER_NOTE',studentVisible:false},
 {kind:'mask',id:'cover',x:2300,y:1480,width:300,height:140,revealed:false,studentVisible:true}
];
