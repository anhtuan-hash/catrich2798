assert.equal(normalized.pages[0].frames.length,2);
assert.equal(normalized.pages[0].frames[0].title,'Reading');
const studentPage=sanitizeStudentPage(normalized.pages[0]);
assert.equal('frames' in studentPage,false,'Frames are owner editing metadata, not a public roster');
assert.equal(studentPage.objects.length,2);
assert.equal(studentPage.objects.at(-1).revealed,false);
assert.equal(JSON.stringify(studentPage).includes('SECRET_TEACHER_NOTE'),false);
const v={x:2200,y:1200,width:800,height:450};
const projected=boardStudentPayload(normalized,null,null,v);
assert.deepEqual(projected.viewport,v);
assert.equal(JSON.stringify(projected).includes('SECRET_TEACHER_NOTE'),false);
assert.equal('frames' in projected.page,false);
assert.equal(boardStudentPayload(normalized,null,null,{x:Infinity,y:-Infinity,width:-9,height:0}).viewport.width,200);
const slides=buildStudentPdfSlides(normalized);
assert.equal(slides.length,2,'Each visible frame becomes a PDF slide');
assert.deepEqual(slides.map(s=>s.viewport.x),[2000,3920]);
assert.equal(JSON.stringify(slides).includes('SECRET_TEACHER_NOTE'),false);
const hiddenFrames=normalizeLesson({...lesson,pages:[{...lesson.pages[0],frames:[a,{...b,hidden:true}]}]},'teacher-12');
assert.equal(buildStudentPdfSlides(hiddenFrames).length,1);
const duplicate=duplicateBoardLesson(lesson,'teacher-12');
