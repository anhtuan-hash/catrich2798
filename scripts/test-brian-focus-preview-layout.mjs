import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=name=>readFileSync(new URL('../src/components/BrianFocus/'+name,import.meta.url),'utf8');
const editor=read('FocusSceneEditor.jsx'),css=read('FocusScenePreviewLayout.css'),app=read('BrianFocus.jsx');
const input=editor.indexOf('<FocusPlaylistUrlInput');
const trigger=editor.indexOf('className="bfc-scene-editor__preview-toggle"');
const preview=editor.indexOf('id="bfc-scene-live-preview"');
const tip=editor.indexOf('className="bfc-scene-editor__tip"');
assert.ok(input>0&&trigger>input&&preview>trigger&&tip>preview,
 'The editable playlist MUST precede the collapsible preview card.');
assert.match(editor,/const \[previewOpen,setPreviewOpen\]=useState\(false\)/);
assert.match(editor,/\{previewOpen&&<div id="bfc-scene-live-preview"/);
assert.match(editor,/aria-expanded=\{previewOpen\}/);
assert.match(editor,/aria-controls="bfc-scene-live-preview"/);
assert.match(editor,/setPreviewOpen\(false\)/);
const sceneIframe=editor.match(/<iframe className="bfc-scene-editor__youtube-player"/g)||[];
assert.equal(sceneIframe.length,1,'Preview player mounts only inside explicitly expanded card.');
const editorBody=editor.indexOf('className="bfc-scene-editor__body"');
assert.ok(editorBody>=0&&editor.indexOf('className="bfc-scene-editor__current"',editorBody)>=0);
assert.match(css,/flex-direction:column/);
assert.match(css,/overflow-y:auto!important/);
assert.match(css,/z-index:125!important/);
assert.match(css,/max-height:185px/);
assert.match(css,/\.bfc-scene-editor__preview>iframe\.bfc-scene-editor__youtube-player/);
assert.match(css,/@media\(max-width:767px\)/);
assert.match(app,/import '\.\/FocusScenePreviewLayout\.css';/);
assert.match(app,/usePersistentFocusYoutube/);
assert.match(app,/startFocusEnter/);
assert.match(app,/startFocusExit/);
console.log('PASS Brian Focus preview: editor first, lazy non-obscuring iframe, compact flow layout, mobile scroll, persistent YouTube and WAAPI.');
