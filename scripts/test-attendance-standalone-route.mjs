import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {hasRouteAccess} from '../src/utils/permissions.js';
import {withAttendanceReadOnlyAccess} from '../src/utils/attendanceReadonlyAccess.js';
const main=readFileSync('src/main.jsx','utf8');
const nav=readFileSync('src/components/GlobalAttendanceNavigationTab.jsx','utf8');
const page=readFileSync('src/pages/AttendanceWorkspace.jsx','utf8');
const style=readFileSync('src/pages/AttendanceWorkspace.css','utf8');
const globalNav=readFileSync('src/components/GlobalFlatNavigation.jsx','utf8');

assert.match(main,/const AttendanceWorkspace = lazy/);
assert.match(main,/'homeroom', 'attendance',/);
assert.match(main,/currentRoute === 'attendance' && currentUser && <AttendanceWorkspace/);
assert.match(main,/withAttendanceReadOnlyAccess\(currentUser\)/);
assert.match(page,/<GlobalAttendanceReadOnlyNavigationTab currentUser=\{currentUser\} standalone/);
assert.match(nav,/standalone = false/);
assert.match(nav,/const workspaceVisible = open \|\| standalone/);
assert.match(nav,/standalone\s*\?\s*<div className="attendance-standalone-root"/);
assert.match(nav,/role=\{standalone \? 'region' : 'dialog'\}/);
assert.match(nav,/if \(\(!standalone && !host\) \|\| !allowed\)/);
assert.match(nav,/open \? createPortal/,'Modal fallback retained for existing integrations');
assert.match(nav,/window\.location\.hash = '#\/attendance';/,'The global attendance navigation button must open the page, not a modal');
assert.match(nav,/window\.location\.hash = '#\/attendance\?tab=quick';/,'Quick attendance shortcut opens the page');
assert.match(nav,/supplementalSession:sessionId/,'External supplemental attendance requests use a routed handoff');
assert.match(nav,/initialLoadSettled/,'Supplemental handoff waits for initial attendance data');
assert.match(nav,/supplementalRouteHandledRef\.current/,'Supplemental handoff must not replay repeatedly');
assert.match(nav,/window\.dispatchEvent\(new CustomEvent\('bes-supplemental-open-rollcall'/,'Supplemental session is reconstructed on the new route');
assert.match(nav,/window\.history\.replaceState\(null, '', '#\/attendance\?tab='/,'Deep links should support all tabs');
assert.match(globalNav,/props\.route !== 'attendance'/,'Never mount duplicate attendance modal on standalone route');
assert.match(style,/display:flex!important;/,'Workspace is a natural full-page flex column');
assert.match(style,/flex-direction:row!important;/,'Desktop top navigation runs horizontally');
assert.match(style,/overflow-x:auto!important;/,'Top navigation scrolls on narrow viewports');
assert.match(style,/height:auto!important;/,'Workspace must not crop page content');
assert.ok(!style.includes('grid-template-columns:240px minmax(0,1fr)'),'Approved mockup does not have a sidebar');
assert.ok(!style.includes('html.bes-attendance-open'),'Standalone page must not lock document scrolling');
assert.match(style,/\.attendance-workspace-page \.attendance-shell\.is-standalone\s*\{/,'Standalone shell must be a normal in-flow region');
assert.match(style,/\.bes-attendance-time-settings\.is-compact-popover/,'Transient teacher-time popup may be fixed on mobile');
const teacher={id:'teacher-123',role:'teacher',permissions:{mode:'custom',allowed:[]}};
assert.equal(hasRouteAccess(teacher,'attendance'),false,'Route must not grant more permissions by default');
assert.equal(hasRouteAccess(withAttendanceReadOnlyAccess(teacher),'attendance'),true,'Read-only legacy access also works on standalone route');
assert.equal(hasRouteAccess(null,'attendance'),false,'Anonymous users cannot access attendance');
console.log('Standalone attendance route, permission safeguards, and modal rollback contract passed.');
