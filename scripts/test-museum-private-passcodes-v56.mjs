import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {encryptGroupPasscode,decryptGroupPasscode} from '../serverless-handlers/_galleryPasscodes.js';
process.env.GCP_HASH_PEPPER='unit-test-pepper-only-not-a-production-secret--this-is-at-least-48-characters-long';
const a='ABCDEFGHIJKLMNOPQRSTUVWXYZ012345',b='SomeOtherHandle56789';
const secret='privatePasscode_ABCDEFGHIJKLMNOPQRSTUVWXYZ';
const ciphertext=encryptGroupPasscode(secret,a);
assert.match(ciphertext,/^v1\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/);
assert.equal(decryptGroupPasscode(ciphertext,a),secret);
assert.equal(decryptGroupPasscode(null,a),null);
assert.throws(()=>decryptGroupPasscode(ciphertext,b));
assert.throws(()=>decryptGroupPasscode(ciphertext.slice(0,-2)+'ab',a));
const api=readFileSync(new URL('../serverless-handlers/gallery-staff.js',import.meta.url),'utf8');
const frontend=readFileSync(new URL('../src/features/immersive-gallery/v3/MuseumLessonFlow.jsx',import.meta.url),'utf8');
const migration=readFileSync(new URL('../supabase/migrations/20261113224000_museum_admin_private_passcodes_v56.sql',import.meta.url),'utf8');
assert.ok(api.includes("if(operation==='reveal-passcodes')"));
assert.ok(api.includes("if(operation==='regenerate-all-passcodes')"));
assert.ok(api.includes("assertAdmin(ctx)"));
assert.ok(api.includes("secret_envelope:encryptGroupPasscode(secret,handle)"));
assert.ok(api.includes("invite_has_passcode:Boolean(inv?.secret_envelope)"));
assert.ok(!api.includes("invite_private_code:"));
assert.ok(frontend.includes('Regenerate all passcodes'));
assert.ok(frontend.includes('Private group passcode'));
assert.ok(frontend.includes('Show all passcodes'));
assert.ok(migration.includes('gcp_admin_rotate_assignment_passcodes'));
assert.ok(migration.includes('grant execute on function public.gcp_admin_rotate_assignment_passcodes'));
console.log('PASS: Museum Lab private passcodes round-trip securely, admin gate and bulk workflow contracts.');
