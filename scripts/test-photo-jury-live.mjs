check(css.includes(':has(> .bss-jury-live)') && css.includes('grid-template-columns:minmax(0,1.65fr)'), 'three-column layout only when jury panel visible');
check(css.includes('@media(max-width:780px)'), 'mobile layout supported');
check(admin.includes("run('admin:visibility',{enabled:session.public_live_enabled===false})"), 'admin switch wired to backend');
check(db.includes('add column if not exists public_live_enabled boolean not null default true'), 'non-destructive migration defaults to owner-approved live');
check(!db.toLowerCase().includes('delete from')&&!db.toLowerCase().includes('drop table'), 'existing judging scores are preserved');
