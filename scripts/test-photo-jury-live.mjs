import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const api=read('supabase/functions/photo-judging/index.ts');
const live=read('src/components/PhotoJuryLive.jsx');
const css=read('src/components/PhotoJuryLive.css');
const gallery=read('src/pages/PhotoSlideshow.jsx');
const admin=read('src/components/PhotoJudgingAdmin.jsx');
