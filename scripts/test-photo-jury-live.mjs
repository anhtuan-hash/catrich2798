const check=(value,message)=>{assert.ok(value,message);console.log('✓ '+message)};
check(api.includes('if (action === "public:live") return publicLiveJury(body);'), 'public endpoint routed separately from judge/admin auth');
check(api.includes('.select("id,is_published")') && api.includes('if (!album?.is_published)'), 'unpublished albums never expose jury information');
check(api.includes('if (!session.public_live_enabled)'), 'admin can disable live public statistics');
check(api.includes('const activeIds = judges.map((j:any)=>j.id);') && api.includes('.is("revoked_at",null)'), 'all active judges with saved scores are eligible, revoked excluded');
check(api.includes('minimumScores:1') && !api.includes('MIN_PUBLIC_SUBMISSIONS'), 'first saved score is visible without submission threshold');
check(api.includes('scoredCount:entries.length') && api.includes('average:round(entries.reduce') && api.includes('criteria:(session.rubric'), 'per-artwork score and category averages include saved scores');
check(!/return send\(\{[^}]*judges:/.test(api.slice(api.indexOf('async function publicLiveJury'),api.indexOf('async function handle'))), 'public API does not return judge rows');
check(api.includes('if (action === "admin:visibility")') && api.includes('await requireAdmin(req)'), 'visibility updates restricted to admin');
check(live.includes("action:'public:live'") && live.includes('POLL_MS = 5000'), 'polls server every 5 seconds');
check(live.includes("find(a=>a.slideId===slideId)"), 'jury summary follows currently displayed artwork');
check(live.includes('if(!snapshot || !snapshot.enabled) return null'), 'visibility toggle hides public panel');
check(live.includes("currentVotes>=1") && live.includes("ready?artwork.criteria.find"), 'UI displays average after the first saved judge score');
check(!live.includes('full_name') && !live.includes('invite_id') && !live.includes('token_hash'), 'guest panel contains no judge identities or tokens');
