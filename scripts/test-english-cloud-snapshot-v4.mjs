import assert from 'node:assert/strict';
import { importCodedCohort } from '../src/features/english-early-warning/earlyWarningEngine.js';
import { buildCloudSnapshot, restoreCloudSnapshot, CLOUD_SCHEMA_VERSION } from '../src/features/english-early-warning/cloudSnapshot.js';
const csv = 'student_id,listening,speaking,reading,writing,recent1,recent2,missing14d\nP001,50,55,60,65,70,65,1';
const cohort = importCodedCohort(csv);
const reviews = {P001:{decision:'confirmed',reviewedAt:'2026-11-14T03:00:00Z',notes:'Not for cloud'}};
const journal = [{studentId:'P001',week:1,skill:'listening',assigned:2,completed:1,checkpointScore:55,observedOn:'2026-11-14',recordedAt:'2026-11-14T03:00:00Z',sequence:1,note:'Private comment'}];
const snapshot = buildCloudSnapshot(cohort,reviews,journal);
assert.equal(snapshot.schemaVersion,CLOUD_SCHEMA_VERSION);
assert.equal(snapshot.learners.length,1);
assert.equal(snapshot.reviews[0].decision,'confirmed');
assert.equal(snapshot.entries[0].week,1);
assert.equal(JSON.stringify(snapshot).includes('Private comment'),false);
assert.equal(JSON.stringify(snapshot).includes('Not for cloud'),false);
const restored = restoreCloudSnapshot(JSON.parse(JSON.stringify(snapshot)));
assert.equal(restored.learners[0].scores.listening,50);
assert.equal(restored.reviews.P001.notes,'');
assert.equal(restored.entries[0].note,'');
assert.throws(()=>restoreCloudSnapshot({...snapshot,schemaVersion:99}),/Unsupported/);
assert.throws(()=>buildCloudSnapshot(cohort, {}, journal),/teacher-confirmed review/);
assert.throws(()=>restoreCloudSnapshot({...snapshot,reviews:[]}),/no confirmed teacher review/);
assert.throws(()=>restoreCloudSnapshot({...snapshot,learners:[{studentId:'PRIVATE_NAME',scores:{}}]}),/Invalid coded learner/);
console.log('[PASS] V4 cloud snapshot strips free text, validates pseudonyms and round trips scores');
