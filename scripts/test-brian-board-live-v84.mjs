import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {newLesson} from '../src/components/BrianBoard/boardModel.js';
import {boardStudentPayload} from '../src/components/BrianBoard/boardPresentation.js';
import {createLiveSession,advanceLiveSession,editLiveQuestion,recordTeacherVote,
 queueTeacherContribution,moderateContribution,clearLiveEntries,aggregateCloud,
 publicLiveSnapshot,LIVE_LIMITS,isLiveActive} from '../src/components/BrianBoard/boardClassroomLive.js';
import {boardRemoteTopic,validateRemoteEnvelope,REMOTE_MAX_BYTES,
 REMOTE_MAX_MESSAGES,REMOTE_DURATION_MS} from '../src/components/BrianBoard/boardRemoteTVCore.js';
const source=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const NOW=Date.now();
const draft=createLiveSession('poll',NOW-1000);
assert.equal(draft.status,'draft');
assert.equal(publicLiveSnapshot(draft,NOW),null);
assert.throws(()=>createLiveSession('unsafe'),/Invalid/);
const edited=editLiveQuestion(draft,'Which option?',Array.from({length:8},(_,i)=>'Choice '+i));
assert.equal(edited.options.length,6);
assert.equal(edited.votes.length,6);
const started=advanceLiveSession(edited,'start',NOW-100);
assert.equal(started.status,'live');
assert.ok(isLiveActive(started,NOW+200));
const voted=recordTeacherVote(started,1,1);
assert.equal(voted.votes[1],1);
assert.equal(recordTeacherVote(voted,99,1),voted);
const noAnswers={...voted,showResults:false};
assert.equal(publicLiveSnapshot(noAnswers,NOW+200).votes,null);
assert.equal(publicLiveSnapshot(voted,NOW+200).votes[1],1);
assert.equal(advanceLiveSession(voted,'pause',NOW+200).status,'paused');
assert.equal(advanceLiveSession(voted,'close',NOW+200).status,'closed');
assert.ok(!isLiveActive(voted,started.expiresAt+1));
const cloud=advanceLiveSession(createLiveSession('cloud',NOW-1000),'start',NOW-100);
const queued=queueTeacherContribution(cloud,'SECRET PENDING <script>alert(1)</script>');
assert.equal(queued.queue.length,1);
assert.equal(publicLiveSnapshot(queued,NOW+20).entries.length,0);
assert.ok(!JSON.stringify(publicLiveSnapshot(queued,NOW+20)).includes('SECRET PENDING'));
const approved=moderateContribution(queued,queued.queue[0].id,true);
assert.equal(approved.queue.length,0);
assert.equal(publicLiveSnapshot(approved,NOW+20).entries.length,1);
const wall=advanceLiveSession(createLiveSession('wall',NOW-1000),'start',NOW-100);
const waiting=queueTeacherContribution(wall,'Comment for review');
const rejected=moderateContribution(waiting,waiting.queue[0].id,false);
assert.equal(rejected.submissions.length,0);
assert.equal(rejected.queue.length,0);
assert.equal(clearLiveEntries(approved).submissions.length,0);
assert.equal(LIVE_LIMITS.notes,60);
assert.deepEqual(aggregateCloud(['Climate','Green','Climate'])[0],{text:'Climate',count:2});
const lesson=newLesson('owner');
lesson.pages[0].objects.push({kind:'text',id:'teacher-secret',x:100,y:120,
 teacherOnly:true,studentVisible:false,text:'PRIVATE ANSWER',fontSize:32});
const payload=boardStudentPayload(lesson,null,null,null,queued);
assert.equal(payload.classroom.kind,'cloud');
assert.ok(!JSON.stringify(payload).includes('SECRET PENDING'));
assert.ok(!JSON.stringify(payload).includes('PRIVATE ANSWER'));
const payloadReady=boardStudentPayload(lesson,null,null,null,approved);
assert.equal(payloadReady.classroom.entries.length,1);
const full={sessionId:'a'.repeat(36),at:NOW,expiresAt:NOW+REMOTE_DURATION_MS,
 payload:payloadReady};
assert.ok(validateRemoteEnvelope(full,NOW+100));
assert.equal(validateRemoteEnvelope({...full,sessionId:'123'},NOW+100),false);
assert.equal(validateRemoteEnvelope({...full,expiresAt:NOW+REMOTE_DURATION_MS*2},NOW+100),false);
assert.equal(validateRemoteEnvelope(full,NOW+48000),false);
assert.equal(REMOTE_MAX_MESSAGES,600);
assert.equal(REMOTE_MAX_BYTES,60000);
assert.equal(boardRemoteTopic('owner-123'),'bbd-owner:owner-123');
const board=source('../src/components/BrianBoard/BrianBoard.jsx');
const teacher=source('../src/components/BrianBoard/BoardClassroomLive.jsx');
const display=source('../src/components/BrianBoard/BoardRemoteTV.jsx');
const tv=source('../public/brian-board-viewer.js');
assert.match(board,/onCreate=\{mode=>/);
assert.match(board,/boardStudentPayload\(lesson,activeActivityId,activityLive,currentViewport,classroomSession\)/);
assert.match(board,/remoteSessionIdRef/);
assert.match(board,/stopRemoteTV/);
assert.match(board,/REMOTE_MAX_MESSAGES/);
assert.match(display,/authorizeSameOwner/);
assert.match(teacher,/moderateContribution/);
assert.match(teacher,/BoardClassroomLivePublic/);
assert.match(tv,/renderClassroomLive\(data\.classroom\)/);
assert.ok(!source('../src/components/BrianBoard/boardRemoteTV.js').includes('service_role'));
assert.ok(!source('../src/components/BrianBoard/boardRemoteTV.js').includes('private:false'));
console.log('PASS Brian Board V8.4: teacher moderation, poll caps, filtered student snapshots, strict private owner-TV envelopes and zero anonymous submissions.');
