import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const page=read('src/pages/AttendanceWorkspace.jsx');
const fix=read('src/pages/AttendanceQuickLayoutFix.css');
const ui=read('src/components/GlobalAttendanceNavigationTab.jsx');
const old=read('src/components/attendance/AttendanceTypographyViews.css');
assert.match(page,/import '\.\/AttendanceQuickLayoutFix\.css';/,'Scoped repair CSS must load with full-page workspace.');
assert.ok(page.indexOf('AttendanceQuickLayoutFix.css')>page.indexOf('AttendanceWorkspaceRebuilt.css'),'Repair CSS must win against existing typography overrides.');
assert.match(old,/minmax\(166px,178px\) 54px!important/,'Root cause is a 54px status column in legacy CSS.');
assert.match(fix,/grid-template-columns:34px minmax\(0,1fr\) 94px 300px!important/,'Roster must reserve full width for 3 buttons.');
assert.match(fix,/grid-template-columns:repeat\(3,minmax\(0,1fr\)\)!important/,'Buttons use equal columns.');
assert.match(fix,/\.attendance-roster-head\s*\{[\s\S]*?grid-template-columns:minmax\(0,1fr\) 94px 300px!important/,'Column headings align with data.');
assert.match(fix,/@media\(max-width:1390px\)/,'Medium screens use stacked status controls.');
assert.match(fix,/@media\(max-width:1040px\)/,'Class list and roster are stacked on narrow screens.');
assert.match(fix,/@media\(max-width:760px\)/,'Phone layout has a dedicated responsive rule.');
assert.match(fix,/\.attendance-class-list\s*\{[\s\S]*?display:flex!important/,'Class list is accessible on mobile, not hidden by legacy CSS.');
assert.match(fix,/\.attendance-roster\s*\{[\s\S]*?overflow:visible!important/,'Long student lists are not clipped.');
assert.match(fix,/\.att-m3-attendance-status\s*\{[\s\S]*?grid-column:1 \/ -1!important/,'Phone controls span full row.');
assert.match(fix,/\.attendance-confirm-bar\s*\{[\s\S]*?flex-direction:column!important/,'Footer remains usable on mobile.');
assert.doesNotMatch(fix,/(^|\n)\s*(html|body|#root)\s*\{/,'Never affect global ESL Brian layout.');
