for (const label of ['Có mặt','Đi trễ','Vắng','Học sinh','Trạng thái']) assert.ok(ui.includes(label),'Keep semantic attendance controls '+label);
console.log('PASS targeted quick attendance CSS: corrected status widths, responsive panes, preserved controls.');
